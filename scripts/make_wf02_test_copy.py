#!/usr/bin/env python3
"""Generate ao_workflows/definitions/tests/wf02_test_short_approval.yml from WF-02 (task T2.12, failure case F-08).

The copy is identical except: its name, a 120-second approval window (so an undecided approval expires during a test),
and Record Approval Decision is told the copy's name (it matches approvals by workflow name). CI checks the copy is
current:  python3 scripts/make_wf02_test_copy.py --check
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ao_workflows/definitions/wf02_closed_loop_remediation.yml"
DST = ROOT / "ao_workflows/definitions/tests/wf02_test_short_approval.yml"
NAME = "AI Governance - WF-02 Test Copy (short approval window)"
WINDOW = 120


class _Dumper(yaml.SafeDumper):
    """Indent list items under their key (the repository's yamllint style)."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def build():
    wf = yaml.safe_load(SRC.read_text())
    wf["name"] = NAME
    wf["description"] = ("TEST ONLY (failure case F-08): WF-02 with a %d-second approval window. Generated by "
                         "scripts/make_wf02_test_copy.py; do not edit." % WINDOW)
    for node in wf["nodes"]:
        if node["type"] == "approval":
            node["decision_window"] = WINDOW
        if node.get("job_template") == "AI Governance - Record Approval Decision":
            node["extra_vars"]["aigov_ao_workflow_name"] = NAME
    header = ("---\n# GENERATED by scripts/make_wf02_test_copy.py from wf02_closed_loop_remediation.yml - do not edit.\n"
              "# TEST ONLY (docs/plan/09 F-08): WF-02 with a %d-second approval window.\n" % WINDOW)
    return header + yaml.dump(wf, Dumper=_Dumper, sort_keys=False, width=110, default_flow_style=False, allow_unicode=True)


def main():
    text = build()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != text:
            sys.exit("%s is out of date: run python3 scripts/make_wf02_test_copy.py" % DST.relative_to(ROOT))
        print("WF-02 test copy is current")
        return
    DST.write_text(text)
    print("wrote", DST.relative_to(ROOT))


if __name__ == "__main__":
    main()
